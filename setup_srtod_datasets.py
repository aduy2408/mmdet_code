def validate_dataset(repo_root: Path, name: str, spec: dict) -> dict:
    result = {"dataset": name, "status": "ready", "warnings": []}
    root = abs_path(repo_root, spec["root"])
    if not root.is_dir():
        raise FileNotFoundError(f"{name}: missing dataset root {root}")
    for split, rel in spec["annotations"].items():
        ann = (
            abs_path(repo_root, spec["annotation_paths"][split])
            if split in spec.get("annotation_paths", {})
            else root / rel
        )
        if not ann.is_file():
            raise FileNotFoundError(f"{name}: missing annotation {ann}")
        payload = json.loads(ann.read_text())
        if not payload.get("images"):
            result["warnings"].append(f"{split} annotation has no images: {ann}")
    for split, rel in spec["images"].items():
        image_root = abs_path(repo_root, rel)
        if not image_root.is_dir():
            archive = abs_path(repo_root, spec.get("archives", {}).get("train" if split != "test" else "test", ""))
            if archive.is_file():
                ann_path = (
                    abs_path(repo_root, spec["annotation_paths"][split])
                    if split in spec.get("annotation_paths", {})
                    else root / spec["annotations"][split]
                )
                refs = [item["file_name"] for item in json.loads(ann_path.read_text())["images"]]
                with tarfile.open(archive) as handle:
                    members = {member.name for member in handle.getmembers() if member.isfile()}
                archive_prefix = "train/" if split != "test" else "test/"
                missing = [ref for ref in refs if archive_prefix + ref not in members]
                if missing:
                    raise FileNotFoundError(
                        f"{name}: {len(missing)} annotation images missing from {archive}; "
                        f"first: {missing[0]}"
                    )
                result["warnings"].append(f"{split} images are archived and need extraction: {archive}")
            else:
                result["warnings"].append(f"{split} image root is not present yet: {image_root}")
        else:
            ann_path = (
                abs_path(repo_root, spec["annotation_paths"][split])
                if split in spec.get("annotation_paths", {})
                else root / spec["annotations"][split]
            )
            refs = [item["file_name"] for item in json.loads(ann_path.read_text())["images"]]
            missing = [ref for ref in refs if not (image_root / ref).is_file()]
            if missing:
                raise FileNotFoundError(
                    f"{name}: {len(missing)} annotation images missing from {image_root}; "
                    f"first: {missing[0]}"
                )
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', default='mmdetection/srtod_setup')
    parser.add_argument('--datasets', default=','.join(DATASETS))
    args = parser.parse_args()
    repo_root = Path(__file__).resolve().parent.parent
    output_dir = abs_path(repo_root, args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    selected = [name.strip() for name in args.datasets.split(',') if name.strip()]
    unknown = sorted(set(selected) - set(DATASETS))
    if unknown:
        raise SystemExit(f'Unknown datasets: {", ".join(unknown)}')

    manifest = {
        'experiment_id': 'srtod_faster_setup',
        'control_config_or_baseline_config': 'unknown: no SR-TOD baseline manifest was previously recorded',
        'variant_config_or_explicit_change': MODEL_BASE,
        'source_commit': '495611b237fc07270d5c7d0f5699afd2ae2488c3',
        'runner': 'SR-TOD/MMDetection tools/train.py, deferred to Marimo',
        'python_executable': '/marimo/mmdet-venv/bin/python (deferred; local .venv-mmdet lacks torch)',
        'split_seed': 42,
        'training_seed(s)': 'unknown until Marimo run plan',
        'model/backbone/pretrained source': 'SRTOD_FasterRCNN, ResNet-50, torchvision://resnet50',
        'image_size, batch_size, epochs, patience, AMP': 'config defaults 1333x800, 2, 12, unknown, unknown',
        'NMS IoU': 0.5,
        'HF repo and remote prefix': 'unknown, no upload requested for setup',
        'required artifacts': ['generated configs', 'dataset manifest'],
        'upload_required': False,
        'datasets': {},
    }
    for name in selected:
        spec = DATASETS[name]
        validation = validate_dataset(repo_root, name, spec)
        config_path = output_dir / f'{name}_srtod_faster_r50_fpn.py'
        config_path.write_text(config_text(repo_root, name, spec), encoding='utf-8')
        validation['config'] = str(config_path)
        validation['annotations'] = {
            split: str(
                abs_path(repo_root, spec['annotation_paths'][split])
                if split in spec.get('annotation_paths', {})
                else (abs_path(repo_root, spec['root']) / rel).resolve()
            )
            for split, rel in spec['annotations'].items()
        }
        validation['image_roots'] = {split: str(abs_path(repo_root, rel)) for split, rel in spec['images'].items()}
        manifest['datasets'][name] = validation
    manifest_path = output_dir / 'experiment_manifest.json'
    manifest_path.write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print(f'Wrote {len(selected)} SR-TOD configs to {output_dir}')
    print(f'Manifest: {manifest_path}')
    for name, details in manifest['datasets'].items():
        print(f'{name}: {details["status"]}' + (f' ({len(details["warnings"])} warnings)' if details['warnings'] else ''))


if __name__ == '__main__':
    main()
